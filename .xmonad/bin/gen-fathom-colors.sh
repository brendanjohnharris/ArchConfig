#!/usr/bin/env bash
set -eu

URL="raw.githubusercontent.com/brendanjohnharris/Fathom.jl/refs/heads/main/test/colors.yaml"
CACHE="${HOME}/.xmonad/cache/fathom.yaml"
HS_OUT="${HOME}/.xmonad/lib/Colors/FathomColors.hs"

mkdir -p "$(dirname "$CACHE")" "$(dirname "$HS_OUT")"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

parse='/^[a-zA-Z_][a-zA-Z0-9_]*:[[:space:]]*$/ {
            name = $1
            sub(/:$/, "", name)
            next
        }
        /^[[:space:]]+[a-zA-Z_]+:[[:space:]]*"#[0-9a-fA-F]+"[[:space:]]*$/ {
            key = $1
            sub(/:$/, "", key)
            val = $2
            gsub(/"/, "", val)
            if (key == "base")
                printf "%s %s\n", name, val
            else
                printf "%s_%s %s\n", name, key, val
        }'

# Download file
if curl -fsSL --max-time 10 "$URL" -o "$tmp"; then
    palette="$(awk "$parse" "$tmp")";
else
    palette="";
fi

if [ -n "$palette" ]; then
    mv "$tmp" "$CACHE";
else
    palette="$(awk "$parse" "$CACHE")";
fi

if [ ! -s "$CACHE" ]; then
    echo "gen-fathom-colors: no cached colors.yaml and download failed" >&2
    exit 1
fi

# 1. Haskell module for xmonad
{
    echo "-- Auto-generated by ~/.xmonad/bin/gen-fathom-colors.sh. Do not edit."
    echo "module Colors.FathomColors where"
    echo
    printf '%s\n' "$palette" | awk '{ printf "%s = \"%s\"\n", $1, $2 }'
} > "$HS_OUT"

# 2. Expand {{name}} tokens in each template.
render_template() {
    local template="$1" output="$2"
    if [ ! -f "$template" ]; then
        echo "gen-fathom-colors: missing template $template" >&2
        return 1
    fi
    awk -v palette="$palette" '
        # Convert a "#RRGGBB" hex string to a requested numeric format.
        #   :r  :g  :b   -> a single 0-255 channel int
        #   :rgb         -> "R G B" as space-separated 0-255 ints
        #   :rgbf        -> "r g b" as space-separated 0-1 floats (4 dp)
        function fmtcolor(hexval, fmt,   h, r, g, b) {
            h = hexval
            sub(/^#/, "", h)
            r = strtonum("0x" substr(h, 1, 2))
            g = strtonum("0x" substr(h, 3, 2))
            b = strtonum("0x" substr(h, 5, 2))
            if (fmt == "r")    return r
            if (fmt == "g")    return g
            if (fmt == "b")    return b
            if (fmt == "rgb")  return r " " g " " b
            if (fmt == "rgbf") return sprintf("%.4f %.4f %.4f", r/255, g/255, b/255)
            print "gen-fathom-colors: unknown format :" fmt " in " FILENAME > "/dev/stderr"
            exit 1
        }
        BEGIN {
            n = split(palette, lines, "\n")
            for (i = 1; i <= n; i++) {
                split(lines[i], kv, " ")
                if (kv[1] != "") colors[kv[1]] = kv[2]
            }
        }
        {
            line = $0
            while (match(line, /\{\{[a-zA-Z_][a-zA-Z0-9_]*(:[a-z]+)?\}\}/)) {
                token = substr(line, RSTART + 2, RLENGTH - 4)
                fmt = ""
                ci = index(token, ":")
                if (ci > 0) {
                    fmt = substr(token, ci + 1)
                    token = substr(token, 1, ci - 1)
                }
                if (token in colors) {
                    repl = (fmt == "") ? colors[token] : fmtcolor(colors[token], fmt)
                    line = substr(line, 1, RSTART - 1) repl substr(line, RSTART + RLENGTH)
                } else {
                    print "gen-fathom-colors: unknown token {{" token "}} in " FILENAME > "/dev/stderr"
                    exit 1
                }
            }
            print line
        }
    ' "$template" > "$output"
}

render_template "${HOME}/.config/xmobar/xmobarrc.template"       "${HOME}/.config/xmobar/xmobarrc"
render_template "${HOME}/.config/xmobar/dual_xmobarrc.template"  "${HOME}/.config/xmobar/dual_xmobarrc"
render_template "${HOME}/.config/alacritty/alacritty.toml.template" "${HOME}/.config/alacritty/alacritty.toml"
render_template "${HOME}/.Xresources.template"                      "${HOME}/.Xresources"
render_template "${HOME}/.config/dunst/dunstrc.template"            "${HOME}/.config/dunst/dunstrc"
render_template "${HOME}/.config/rofi/themes/fathom.rasi.template"  "${HOME}/.config/rofi/themes/fathom.rasi"
render_template "${HOME}/.config/gtk-3.0/gtk.css.template"          "${HOME}/.config/gtk-3.0/gtk.css"
render_template "${HOME}/.config/gtk-4.0/gtk.css.template"          "${HOME}/.config/gtk-4.0/gtk.css"

# CLI tools (atuin/yazi/zellij/lazygit/tealdeer/sioyek). mkdir for a fresh
# machine where the tool hasn't created its config dir yet.
mkdir -p "${HOME}/.config/atuin/themes" "${HOME}/.config/yazi" \
         "${HOME}/.config/zellij" "${HOME}/.config/lazygit" \
         "${HOME}/.config/tealdeer" "${HOME}/.config/sioyek"
render_template "${HOME}/.config/atuin/themes/fathom.toml.template"  "${HOME}/.config/atuin/themes/fathom.toml"
render_template "${HOME}/.config/yazi/theme.toml.template"           "${HOME}/.config/yazi/theme.toml"
render_template "${HOME}/.config/zellij/config.kdl.template"         "${HOME}/.config/zellij/config.kdl"
render_template "${HOME}/.config/lazygit/config.yml.template"        "${HOME}/.config/lazygit/config.yml"
render_template "${HOME}/.config/tealdeer/config.toml.template"      "${HOME}/.config/tealdeer/config.toml"
render_template "${HOME}/.config/sioyek/prefs_user.config.template"  "${HOME}/.config/sioyek/prefs_user.config"

# fish: colours live in an auto-sourced conf.d snippet. fish wants hex WITHOUT a
# leading '#', so strip it from the rendered values (leaves '#' comments intact).
fish_colors_out="${HOME}/.config/fish/conf.d/fathom_colors.fish"
mkdir -p "$(dirname "$fish_colors_out")"
render_template "${HOME}/.config/fish/conf.d/fathom_colors.fish.template" "$fish_colors_out"
sed -E -i 's/#([0-9A-Fa-f]{6})\b/\1/g' "$fish_colors_out"

# 3. Live-reload running apps when invoked inside an X session (no-op headless).
if [ -n "${DISPLAY:-}" ]; then
    [ -f "${HOME}/.Xresources" ] && xrdb -merge "${HOME}/.Xresources" >/dev/null 2>&1 || true
    command -v dunstctl >/dev/null 2>&1 && dunstctl reload >/dev/null 2>&1 || true
fi

echo "gen-fathom-colors: success" >&2
